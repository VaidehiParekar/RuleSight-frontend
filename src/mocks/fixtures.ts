function gap(
  code: string,
  obligation: string,
  gap_type: Gap["gap_type"],
  title: string,
  description: string,
  controls: string[],
  evidence: string[],
  factors: { criticality: number; severity: number; urgency?: number },
  status: Gap["status"],
  change_id: string | null = null,
): Gap {
  const urgency = factors.urgency ?? 1;
  const score = factors.criticality * factors.severity * urgency;
  const priority = score >= 6 ? "P1" : score >= 3 ? "P2" : "P3";
  return {
    id: code.toLowerCase(),
    code,
    obligation_id: obligation,
    gap_type,
    title,
    description,
    control_ids: controls,
    evidence_ids: evidence,
    origin: change_id ? "change" : "initial",
    change_id,
    risk_factors: {
      criticality: factors.criticality,
      severity: factors.severity,
      urgency,
      rule_version: "v1",
    },
    risk_score: score,
    priority,
    status,
  };
}

